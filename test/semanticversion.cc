#include "stdafx.h"

#include "gtest/gtest.h"

#include "Versioning/semanticversion.h"

namespace pg
{
    namespace test
    {
        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, default_constructor)
        {
            SemanticVersion v;

            EXPECT_EQ(v.major, 1);
            EXPECT_EQ(v.minor, 0);
            EXPECT_EQ(v.patch, 0);
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, parameterized_constructor)
        {
            SemanticVersion v(2, 3, 4);

            EXPECT_EQ(v.major, 2);
            EXPECT_EQ(v.minor, 3);
            EXPECT_EQ(v.patch, 4);
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, string_constructor_valid)
        {
            SemanticVersion v("3.5.7");

            EXPECT_EQ(v.major, 3);
            EXPECT_EQ(v.minor, 5);
            EXPECT_EQ(v.patch, 7);
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, string_constructor_invalid)
        {
            SemanticVersion v("garbage");

            EXPECT_EQ(v.major, 1);
            EXPECT_EQ(v.minor, 0);
            EXPECT_EQ(v.patch, 0);
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, parse_valid)
        {
            SemanticVersion v;
            bool result = v.parse("2.4.6");

            EXPECT_TRUE(result);
            EXPECT_EQ(v.major, 2);
            EXPECT_EQ(v.minor, 4);
            EXPECT_EQ(v.patch, 6);
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, parse_invalid)
        {
            SemanticVersion v(5, 5, 5);
            bool result = v.parse("not.a.version");

            EXPECT_FALSE(result);
            EXPECT_EQ(v.major, 1);
            EXPECT_EQ(v.minor, 0);
            EXPECT_EQ(v.patch, 0);
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, parse_empty)
        {
            SemanticVersion v(5, 5, 5);
            bool result = v.parse("");

            EXPECT_FALSE(result);
            EXPECT_EQ(v.major, 1);
            EXPECT_EQ(v.minor, 0);
            EXPECT_EQ(v.patch, 0);
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, parse_partial)
        {
            SemanticVersion v(5, 5, 5);
            bool result = v.parse("1.2");

            EXPECT_FALSE(result);
            EXPECT_EQ(v.major, 1);
            EXPECT_EQ(v.minor, 0);
            EXPECT_EQ(v.patch, 0);
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, to_string)
        {
            SemanticVersion v(1, 2, 3);

            EXPECT_EQ(v.toString(), "1.2.3");
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, to_string_zeros)
        {
            SemanticVersion v(0, 0, 0);

            EXPECT_EQ(v.toString(), "0.0.0");
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, equality)
        {
            EXPECT_TRUE(SemanticVersion(1, 2, 3) == SemanticVersion(1, 2, 3));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, inequality_different_major)
        {
            EXPECT_TRUE(SemanticVersion(1, 2, 3) != SemanticVersion(2, 2, 3));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, inequality_different_minor)
        {
            EXPECT_TRUE(SemanticVersion(1, 2, 3) != SemanticVersion(1, 3, 3));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, inequality_different_patch)
        {
            EXPECT_TRUE(SemanticVersion(1, 2, 3) != SemanticVersion(1, 2, 4));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, less_than_major)
        {
            EXPECT_TRUE(SemanticVersion(1, 9, 9) < SemanticVersion(2, 0, 0));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, less_than_minor)
        {
            EXPECT_TRUE(SemanticVersion(1, 2, 9) < SemanticVersion(1, 3, 0));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, less_than_patch)
        {
            EXPECT_TRUE(SemanticVersion(1, 2, 3) < SemanticVersion(1, 2, 4));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, not_less_than_equal)
        {
            EXPECT_FALSE(SemanticVersion(1, 2, 3) < SemanticVersion(1, 2, 3));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, greater_than)
        {
            EXPECT_TRUE(SemanticVersion(2, 0, 0) > SemanticVersion(1, 9, 9));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, less_equal)
        {
            EXPECT_TRUE(SemanticVersion(1, 2, 3) <= SemanticVersion(1, 2, 3));
            EXPECT_TRUE(SemanticVersion(1, 2, 3) <= SemanticVersion(1, 2, 4));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, greater_equal)
        {
            EXPECT_TRUE(SemanticVersion(1, 2, 3) >= SemanticVersion(1, 2, 3));
            EXPECT_TRUE(SemanticVersion(1, 2, 4) >= SemanticVersion(1, 2, 3));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, is_major_bump)
        {
            EXPECT_TRUE(SemanticVersion(2, 0, 0).isMajorBumpFrom(SemanticVersion(1, 5, 3)));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, is_not_major_bump_same_major)
        {
            EXPECT_FALSE(SemanticVersion(1, 5, 0).isMajorBumpFrom(SemanticVersion(1, 2, 0)));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, is_minor_bump)
        {
            EXPECT_TRUE(SemanticVersion(1, 3, 0).isMinorBumpFrom(SemanticVersion(1, 2, 5)));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, is_not_minor_bump_different_major)
        {
            EXPECT_FALSE(SemanticVersion(2, 3, 0).isMinorBumpFrom(SemanticVersion(1, 2, 0)));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, is_patch_bump)
        {
            EXPECT_TRUE(SemanticVersion(1, 2, 4).isPatchBumpFrom(SemanticVersion(1, 2, 3)));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, is_not_patch_bump_different_minor)
        {
            EXPECT_FALSE(SemanticVersion(1, 3, 0).isPatchBumpFrom(SemanticVersion(1, 2, 5)));
        }

        // ----------------------------------------------------------------------------------------
        // ---------------------------        Test separator        -------------------------------
        // ----------------------------------------------------------------------------------------
        TEST(semantic_version_test, parse_roundtrip)
        {
            SemanticVersion v;
            v.parse("5.10.15");

            EXPECT_EQ(v.toString(), "5.10.15");
        }
    }
}
